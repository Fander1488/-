score = int(input("Введіть кількість отриманих балів на екзамені: "))

if 0 <= score <= 49:
    print("Результат: незадовільно.")
elif 50 <= score <= 69:
    print("Результат: задовільно.")
elif 70 <= score <= 89:
    print("Результат: добре.")
elif 90 <= score <= 100:
    print("Результат: відмінно.")
else:
    print("Помилка! Бали повинні бути в діапазоні від 0 до 100.")
